/** Noe som står på et punkt ute: kum, lys i støttemuren eller pullert. */
export interface SitePoint {
  kind: "kum" | "lys" | "pullert";
  name: string;
  at: Pt;
}

export interface Site {
  /** Eiendomsgrensen for hele tomta (alle tre husene). */
  boundary: Pt[];
  /** Vår del av tomta: øst for skillet mot Hus A og Hus B. Kartet viser bare dette. */
  lot: Pt[];
  /** Plen og beplantning. */
  green: Pt[][];
  /** Grus og asfalt: gårdsplass og innkjørsel. */
  paving: Pt[][];
  /** Belegningsstein: snuplassen. */
  pavers: Pt[][];
  /** Bruddskifer: terrassen sør for Hus C og stien nord for gårdsplassen. */
  stone: Pt[][];
  /** Fjell i dagen. */
  rock: Pt[][];
  /** Regnbedet. */
  rainbed: Pt[];
  /** Støttemurer (streker langs murene). */
  walls: Pt[][];
  /** Kanter, trinn og trapper (tynne streker). */
  details: Pt[][];
  /** Nabohusene på tomta (Hus A og Hus B), med navn. */
  houses: { name: string; pts: Pt[]; at: Pt }[];
  /** Trær og busker: [x, y, radius]. */
  trees: [number, number, number][];
  /** Kummer, lys og pullerter. */
  points: SitePoint[];
  /** Navn på flatene. */
  labels: { text: string; at: Pt }[];
  /** Veiene rundt, med plassering og vinkel (grader). */
  roads: { name: string; at: Pt; angle: number }[];
}

